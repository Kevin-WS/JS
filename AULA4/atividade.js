
let dia = Number(prompt("Digite um numero de 1 a 7"))

switch (dia) {
    case 1:
        alert("Segunda")
        console.log("Numero 1 = Segunda");
        break;
    case 2:
        alert("Terça")
        console.log("Numero 2 = Terla");
        break;
    case 3:
        alert("Quarta")
        console.log("Numero 3 = Quarta");
        break;
    case 4:
        alert("Quinta")
        console.log("Numero 4 = Quinta");
        break;
    case 5:
        alert("Sexta")
        console.log("Numero 5 = Sexta");
        break;
    case 6:
        alert("Sabado")
        console.log("Numero 6 = Sabado");
        break;
    case 7:
        alert("Domingo")
        console.log("Numero 7 = Domingo");
        break;

    default:
        alert("Numero sem definiçaõ")
        break;
}
